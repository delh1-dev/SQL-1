CREATE TABLE IF NOT EXISTS school (

    id INT NOT NULL AUTO_INCREMENT,
    name VARCHAR(100) NOT NULL,
    capacity INT DEFAULT NULL,
    country VARCHAR(250) NOT NULL,
    PRIMARY KEY (id)
);
